-- ============================================================================
-- 迁移 2: 电桩状态语义升级
-- 旧值 {0空闲, 1使用中, 2故障} 改为新值 {0空闲, 1已连接, 2充电中, 3故障}
--   旧 1(使用中) -> 新 2(充电中);  旧 2(故障) -> 新 3(故障);  旧 0 不变
-- ============================================================================
UPDATE charger SET status = CASE status
    WHEN 1 THEN 2
    WHEN 2 THEN 3
    ELSE status
END;
